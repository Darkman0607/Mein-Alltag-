import assert from 'node:assert/strict';
import {QUICK_TEMPLATES,normalizeArticleName,exactNameMatches,compatibleMatches,similarMatches,recentlyUsedItems,quickBookingDefaults} from './modules/lagerhaus-quick.js';
import {upsertItem} from './modules/lagerhaus-items.js';
import {bookStock,stockTotal} from './modules/lagerhaus-stock.js';
import {quantityLabel} from './modules/lagerhaus-consumption.js';
import {materialSources} from './modules/putzmanager-cleaning.js';
import {renderLagerhaus} from './modules/lagerhaus-app.js';
import {renderLagerartikel} from './modules/lagerhaus-items-view.js';
import {templatesFor} from './modules/lagerhaus-templates.js';
const id=()=>crypto.randomUUID();
assert(QUICK_TEMPLATES.length>=5);
assert(QUICK_TEMPLATES.some(x=>x.id==='gloves'&&x.unitMode==='packs'&&x.packSize===100));
assert(QUICK_TEMPLATES.some(x=>x.id==='screws'&&x.unit==='stk'));
assert(QUICK_TEMPLATES.some(x=>x.id==='cables'&&x.unit==='m'));
assert(templatesFor('verbrauch').some(x=>x.id==='verbrauch-handschuhe'));
assert(templatesFor('verbrauch').some(x=>x.id==='verbrauch-muellbeutel'));
const glove={name:'Nitrilhandschuhe M',unit:'stk',quantity:100,type:'verbrauch',locationId:'',condition:'gut',minimumStock:0,packSize:100,properties:{}};
const item=upsertItem([],{...glove},{makeId:()=> 'glove-id'}).items[0];
assert.equal(normalizeArticleName('  NITRILHANDSCHUHE---M '),'nitrilhandschuhe m');
assert.equal(exactNameMatches([item],'nitrilhandschuhe--m').length,1);
assert.equal(exactNameMatches([item],'nitrilhandschuhe l').length,0);
assert.equal(compatibleMatches([item],'nitrilhandschuhe M','stk','verbrauch').length,1);
assert.equal(compatibleMatches([item],'nitrilhandschuhe M','pack','verbrauch').length,0);
assert.equal(similarMatches([item],'Nitrilhandschuhe').length,1);
assert.equal(quickBookingDefaults(item,'issue').mode,'pairs');
assert.equal(quickBookingDefaults(item,'receive').mode,'packs');
assert.equal(quickBookingDefaults({...item,name:'Schrauben M6'},'issue').mode,'units');
assert.equal(quickBookingDefaults({...item,name:'Reiniger',unit:'ml'},'issue').chips[0][0],50);
let current=item;
let booked=bookStock(current,{type:'receive',quantity:1,unitMode:'packs',toId:''},new Set(['']),{makeId:id});
current=booked.item;assert.equal(stockTotal(current),200);assert.equal(booked.event.quantity,100);
booked=bookStock(current,{type:'issue',quantity:2,unitMode:'pairs',fromId:''},new Set(['']),{makeId:id});
current=booked.item;assert.equal(stockTotal(current),196);assert.equal(booked.event.quantity,4);
assert.equal(quantityLabel(current,stockTotal(current)),'98 Paar (196 Stück)');
assert.throws(()=>bookStock(current,{type:'issue',quantity:99,unitMode:'pairs',fromId:''},new Set([''])),/Nicht genügend/);
const withAnother={...current,id:'other',name:'Badreiniger',createdAt:'2026-11-01T00:00:00Z',updatedAt:'2026-11-12T00:00:00Z'};
const newer={...current,id:'glove-id',createdAt:'2026-11-03T00:00:00Z',updatedAt:'2026-11-13T00:00:00Z'};
assert.equal(recentlyUsedItems([withAnother,newer])[0].id,'glove-id');
assert.equal(materialSources([current],[],[])[0].available,196);
const home=renderLagerhaus();
assert(home.includes('lagerFastRecent')&&home.includes('lagerFastBooking')&&home.includes('data-quick-template')&&home.includes('lagerFastDuplicate'));
assert(renderLagerartikel().includes('Meine Artikel'));
const stockJs=(await import('node:fs/promises')).readFile;
const source=await stockJs(new URL('./modules/lagerhaus-app.js',import.meta.url),'utf8');
assert(source.includes('data-fast-stock=')&&source.includes('Entnahme bestätigen')&&source.includes('duplicateChoice')&&source.includes('mutateModuleValues'));
const view=await stockJs(new URL('./modules/lagerhaus-items-view.js',import.meta.url),'utf8');
assert(view.includes('data-stock-preset')&&view.includes('compatibleMatches(items,value.name'));
const sw=await stockJs(new URL('./sw.js',import.meta.url),'utf8');
assert(sw.includes("'./modules/lagerhaus-quick.js'"));
console.log('PASS LUX02: recent order, normalized duplicates, compatible matching, item templates, one-pair/pack presets, bookStock, stock safety, cleaning integration, DOM structure, offline precache');
