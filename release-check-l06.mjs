import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {templatesFor,propertiesFor,templateById,normalizeProperties,detailedProperties} from './modules/lagerhaus-templates.js';
import {validateItem,upsertItem,deleteItem} from './modules/lagerhaus-items.js';
const root=path.dirname(fileURLToPath(import.meta.url));
const read=p=>fs.readFileSync(path.join(root,p),'utf8');
const v=JSON.parse(read('version.json'));
assert.deepEqual([v.version,v.build],['0.9.0','L09']);
assert.match(read('assets/app.js'),/APP_VERSION='0.9.0'/);
assert.match(read('sw.js'),/CACHE='mein-alltag-v0-9-0'/);
assert.match(read('sw.js'),/lagerhaus-templates.js/);
for(const type of ['geraet','verbrauch','einzel','sonstiges']){
 assert(Array.isArray(templatesFor(type)));
 assert(Array.isArray(propertiesFor(type)));
 for(const t of templatesFor(type))assert.equal(templateById(type,t.id),t);
 assert.equal(templateById(type,'invalid'),null);
}
assert.equal(templatesFor('geraet').length,3);
assert.equal(templatesFor('verbrauch').length,3);
assert.equal(templatesFor('einzel').length,2);
assert.equal(templatesFor('sonstiges').length,0);
const base={name:'  Alte Maschine  ',type:'geraet',category:'',quantity:1,unit:'stk',condition:'gut',locationId:'',brand:'',articleNumber:'',note:''};
const oldL05={id:'old-id',code:'A-0001',name:'Altartikel',type:'geraet',category:'Werkzeuge',quantity:1,unit:'stk',condition:'gut',locationId:'',brand:'',articleNumber:'',note:'alt',createdAt:'2026-10-26',updatedAt:'2026-10-26'};
const persisted=upsertItem([oldL05],{...oldL05,name:'Alte Maschine'}, {id:'old-id',rooms:[],areas:[],sequence:1,now:'2026-10-27'});
assert.deepEqual([persisted.items[0].id,persisted.items[0].code,persisted.items[0].createdAt],['old-id','A-0001','2026-10-26']);
assert.deepEqual(persisted.items[0].properties,{});
assert.equal(persisted.items[0].quantity,1);
const created=upsertItem(persisted.items,{...base,properties:{serialNumber:'  S-ABC  ',model:' GSR 18V ',purchaseDate:'2024-02-29',extra:'untrusted'}},{makeId:()=> 'device-new',rooms:[],areas:[],sequence:1,now:'2026-10-27'});
assert.equal(created.items.at(-1).code,'A-0002');
assert.deepEqual(created.items.at(-1).properties,{model:'GSR 18V',serialNumber:'S-ABC',purchaseDate:'2024-02-29'});
assert.equal(detailedProperties(created.items.at(-1)).length,3);
assert.throws(()=>normalizeProperties('geraet',{purchaseDate:'2025-02-29'}),/Datum/);
assert.throws(()=>normalizeProperties('geraet',{model:'x'.repeat(101)}),/maximal/);
assert.throws(()=>normalizeProperties('verbrauch',{expiryDate:'2026-13-01'}),/Datum/);
assert.deepEqual(normalizeProperties('einzel',{color:'  Rot ',material:' Stahl ',serialNumber:'no'}),{color:'Rot',material:'Stahl'});
assert.deepEqual(normalizeProperties('sonstiges',{foo:'x'}),{});
const updated=upsertItem(created.items,{...created.items.at(-1),type:'verbrauch',properties:{expiryDate:'2027-06-15',model:'muss weg'}},{id:'device-new',sequence:2});
assert.deepEqual(updated.items.at(-1).properties,{expiryDate:'2027-06-15'});
assert.equal(updated.items.at(-1).code,'A-0002');
assert.equal(deleteItem(updated.items,'device-new')[0].id,'old-id');
const quick=upsertItem([], {...base,name:'Schrauben',type:'verbrauch',properties:undefined}, {makeId:()=> 'quick-1',rooms:[],areas:[],sequence:0});
assert.deepEqual(quick.items[0].properties,{});
assert.equal(quick.items[0].name,'Schrauben');
const ui=read('modules/lagerhaus-items-view.js');
assert.match(ui,/lagerItemTemplate/);
assert.match(ui,/bindTemplates\(el\)/);
assert.match(ui,/name="type"/);
assert.match(ui,/lagerItemDetails/);
assert.match(ui,/propertiesFor\(value.type\)/);
assert.match(ui,/esc\(p.value\)/);
assert.match(ui,/templateById\(type.value,template.value\)/);
assert.match(ui,/Schnellerfassung/);
assert.equal(read('assets/database.js').includes("DB_NAME = 'mein-alltag-v0'"),true);
console.log('PASS L06: 3 typed forms, 8 presets, legacy L05 data, new properties, date checks, escaping, type switch, simple quick entry, stable IDs, version/offline cache.');
