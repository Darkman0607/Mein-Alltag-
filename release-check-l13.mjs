import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {CATEGORY_KEY,CATEGORY_COLORS,CATEGORY_STARTERS,searchKey,cleanTags,validateCategory,addCategory,editCategory,removeCategory,bulkAssign,toggleFavorite,migrateCategories,matchesItem,filterItems} from './modules/lagerhaus-categories.js';
import {upsertItem} from './modules/lagerhaus-items.js';
import {stockTotal} from './modules/lagerhaus-stock.js';
const next=(()=>{let n=0;return ()=>`test-${++n}`})();
const stock={id:'i1',code:'A-0001',name:'Nitrilhandschuhe Größe L',type:'verbrauch',category:'Handschuhe',quantity:37,unit:'stk',packSize:100,locationId:'r1',stockLocations:[{locationId:'r1',quantity:37}],containers:[{id:'c1',locationId:'r1',remaining:37,capacity:100}],favorite:false};
const other={id:'i2',code:'A-0002',name:'Besen',type:'geraet',category:'Werkzeuge',quantity:1,unit:'stk',locationId:'r1',stockLocations:[{locationId:'r1',quantity:1}]};
const base=[stock,other];const migration=migrateCategories(base,[],next);
assert.equal(migration.categories.length,2);assert(migration.items.every(i=>i.categoryId));
assert.equal(migrateCategories(migration.items,migration.categories,next).changed,false);
assert.equal(stockTotal(migration.items[0]),37);
assert.equal(migration.items[0].containers[0].remaining,37);
assert.equal(searchKey('GRÖSSE ß'), 'groesse ss');
assert.deepEqual(cleanTags('Handschuhe,Handschuhe, Nitril; Schutz'),['Handschuhe','Nitril','Schutz']);
let cats=addCategory(migration.categories,{name:'Schutzkleidung',icon:'🧤',color:'blue',aliases:'PSA, PPE'},next);
const parent=cats.at(-1);cats=addCategory(cats,{name:'Einweghandschuhe',parentId:parent.id,color:'teal'},next);
const child=cats.at(-1);
assert.throws(()=>addCategory(cats,{name:'Einweghandschuhe',parentId:parent.id},next),/existiert/);
assert.throws(()=>editCategory(cats,migration.items,parent.id,{name:'Schutzkleidung',parentId:child.id}),/Unterkategorie/);
let assigned=bulkAssign(migration.items,new Set(['i1']),child.id,cats);
assert.equal(assigned[0].categoryId,child.id);assert.equal(stockTotal(assigned[0]),37);
assert.equal(filterItems(assigned,{categoryId:parent.id},cats).length,1);
assert.throws(()=>removeCategory(cats,assigned,child.id),/verwendet/);
let renamed=editCategory(cats,assigned,child.id,{name:'Nitrilhandschuhe',parentId:parent.id,icon:'🧤',color:'blue',aliases:'gloves;Handschuh'});
assert.equal(renamed.items[0].category,'Nitrilhandschuhe');
assert(matchesItem(renamed.items[0],'gloves',renamed.categories));
assert(matchesItem(renamed.items[0],'Groesse L',renamed.categories));
assert.equal(stockTotal(renamed.items[0]),37);
let fav=toggleFavorite(renamed.items,'i1');assert.equal(filterItems(fav,{favorites:true},renamed.categories).length,1);
assert.equal(toggleFavorite(fav,'i1')[0].favorite,false);
assert.equal(filterItems(fav,{search:'Nitril groesse',type:'verbrauch',sort:'name'},renamed.categories).length,1);
assert.equal(filterItems(fav,{type:'geraet'},renamed.categories).length,1);
const created=upsertItem(fav,{name:'Handschuhbox',categoryId:child.id,tags:'Einweg, PSA',favorite:'on',quantity:37,unit:'stk',type:'verbrauch',packSize:100},{rooms:[{id:'r1',name:'Lager',furniture:[]}],areas:[],makeId:next,categories:renamed.categories,sequence:2});
const latest=created.items.at(-1);assert.equal(latest.category,'Nitrilhandschuhe');assert.deepEqual(latest.tags,['Einweg','PSA']);assert.equal(latest.favorite,true);assert.equal(stockTotal(latest),37);
assert.throws(()=>upsertItem(fav,{name:'Fehler',categoryId:'ghost',quantity:1,unit:'stk'},{rooms:[],categories:renamed.categories,makeId:next}),/existiert/);
const edited=upsertItem(created.items,{...latest,name:'Handschuhbox 2',tags:'neu,PSA',quantity:37},{id:latest.id,rooms:[{id:'r1',name:'Lager',furniture:[]}],categories:renamed.categories,sequence:created.sequence});
assert.equal(stockTotal(edited.items.at(-1)),37);
assert.equal(edited.items.at(-1).categoryId,child.id);
let emptied=bulkAssign(renamed.items,['i1'],'',renamed.categories);
assert.equal(emptied[0].categoryId,'');assert.equal(stockTotal(emptied[0]),37);
const withoutChild=removeCategory(renamed.categories,emptied,child.id);
assert(!withoutChild.some(c=>c.id===child.id));
assert(readFileSync('sw.js','utf8').includes("'./modules/lagerhaus-categories.js'"));
assert(JSON.parse(readFileSync('version.json','utf8')).version==='0.13.0');
const view=readFileSync('modules/lagerhaus-items-view.js','utf8');
for(const feature of ['lagerFilterCategory','lagerFilterFav','lagerFilterSort','lagerFilterTag','lagerBulkApply','lagerCategoryForm','data-favorite-toggle','name="categoryId"','name="tags"'])assert(view.includes(feature),feature);
console.log('L13 PASS: migration, ID stability, tag normalization, filtering, colors, category hierarchy, favorites, bulk assign, stock conservation and integration.');
