import assert from 'node:assert/strict';
import fs from 'node:fs';
import {pairEligible,pairsLabel,consumptionQuantity} from './modules/lagerhaus-consumption.js';
import {addContainer,updateContainer,assertTrackedBalances} from './modules/lagerhaus-tracking.js';
import {stockTotal} from './modules/lagerhaus-stock.js';
const item={id:'i1',code:'A1',name:'Nitrilhandschuhe',type:'verbrauch',unit:'stk',quantity:100,stockLocations:[{locationId:'c1',quantity:100}],containers:[]};
const ids=new Set(['c1']);let n=0;const newid=()=>String(++n);
assert(pairEligible(item));assert.equal(pairsLabel(100),'50 Paar');
assert.equal(consumptionQuantity(item,3,'pairs'),6);
assert.throws(()=>consumptionQuantity(item,1.5,'pairs'));
let out=addContainer([item],item.id,{capacity:100,locationId:'c1',source:'existing'},ids,{makeId:newid,makeEventId:newid});
let id=out.items[0].containers[0].id;
let after=updateContainer(out.items,item.id,id,'consume',{quantity:consumptionQuantity(item,3,'pairs')},ids,{makeEventId:newid});
assert.equal(stockTotal(after.items[0]),94);assertTrackedBalances(after.items[0]);
assert.equal(pairsLabel(93),'46 Paar + 1 einzelner Handschuh');
const app=fs.readFileSync('modules/lagerhaus-app.js','utf8');
assert(app.includes('lager-shelf-modal')&&app.includes('data-room-preview')&&app.includes('touchmove'));
const ver=JSON.parse(fs.readFileSync('version.json','utf8'));
assert.equal(ver.version,'0.12.2');assert.equal(ver.build,'L12-HF02');
const sw=fs.readFileSync('sw.js','utf8');
assert(sw.includes('lagerhaus-consumption.js')&&sw.includes('mein-alltag-v0-12-2'));
console.log('PASS L12-HF01 – units, containers, user interface bindings, version.');
